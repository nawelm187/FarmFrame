// Builds src/lib/menuTerms.ts: only the 29 menu/page names of the 8 non-English dictionaries, so the search module does not import whole dictionaries (audit R1).
// Run: node scripts/gen-menu-terms.mjs        Check only (exit 1 if the file is out of date): node scripts/gen-menu-terms.mjs --check
import { readFileSync, writeFileSync } from "node:fs";
const UI = ["warframes", "weapons", "mods", "companions", "archwings", "railjack", "relics", "parts", "enemies", "resources", "lore", "patchNotes", "kdrives", "starterGuides", "helminth", "farmPlan", "farmingMethods", "syndicates", "resourceFinder", "planner", "rotations", "fissures", "invasions", "alerts", "mastery", "roadmap", "builds", "tracking", "dataSources"];
const LANGS = ["de", "es", "fr", "it", "ja", "pt", "ru", "zh"];
const pick = (code, key) => {
  const src = readFileSync(new URL(`../src/i18n/${code}.ts`, import.meta.url), "utf8");
  const m = new RegExp(`^\\s*${key}:\\s*("(?:[^"\\\\]|\\\\.)*"),?\\s*$`, "m").exec(src);
  if (!m) throw new Error(`${code}.ts: key "${key}" not found as a one-line string`);
  return JSON.parse(m[1]);
};
let out = "// GENERATED by scripts/gen-menu-terms.mjs from src/i18n/*.ts: do not edit by hand. A test fails if it is out of date.\n// Menu and page names in the 8 non-English languages, for the search (see multilang.ts).\nexport const MENU_KEYS = " + JSON.stringify(UI) + " as const;\nexport const MENU_TERMS: Record<string, Record<(typeof MENU_KEYS)[number], string>> = {\n";
for (const c of LANGS) out += `  ${c}: ${JSON.stringify(Object.fromEntries(UI.map(k => [k, pick(c, k)])))},\n`;
out += "};\n";
const path = new URL("../src/lib/menuTerms.ts", import.meta.url);
if (process.argv.includes("--check")) {
  let cur = ""; try { cur = readFileSync(path, "utf8"); } catch { /* missing */ }
  if (cur !== out) { console.error("src/lib/menuTerms.ts is out of date: run node scripts/gen-menu-terms.mjs"); process.exit(1); }
  console.log("menuTerms.ts is up to date");
} else { writeFileSync(path, out); console.log("written src/lib/menuTerms.ts", out.length, "bytes"); }
